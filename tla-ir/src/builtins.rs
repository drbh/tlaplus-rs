impl Builtin {
    pub fn in_module(self, module: Option<&str>) -> Option<Self> {
        match (self, module) {
            (Self::Any, Some("TLC" | "AnySet"))
            | (Self::JavaTime, Some("TLC"))
            | (Self::ModelValue, Some("TLCExt")) => Some(self),
            (Self::Any | Self::JavaTime | Self::ModelValue, _) => None,
            _ => Some(self),
        }
    }
    pub fn from_name(name: &str) -> Option<Self> {
        use Builtin::*;
        Some(match name {
            "'" => Prime,
            "ToString" => ToString,
            "ToJson" => ToJson,
            "ToJsonArray" => ToJsonArray,
            "ToJsonObject" => ToJsonObject,
            "JsonSerialize" => JsonSerialize,
            "Print" => Print,
            "PrintT" => PrintT,
            "TLCCache" => TlcCache,
            "TLCGet" => TlcGet,
            "TLCGetOrDefault" => TlcGetOrDefault,
            "TLCSet" => TlcSet,
            "TLCFP" => TlcFingerprint,
            "TLCEvalDefinition" => TlcEvalDefinition,
            "JavaTime" => JavaTime,
            "TLCModelValue" => ModelValue,
            "ENABLED" => Enabled,
            "IsInjective" => IsInjective,
            "AntiFunction" => AntiFunction,
            "\\oplus" => BagAdd,
            "\\ominus" => BagDifference,
            "\\sqsubseteq" => BagSubset,
            "BagUnion" => BagUnion,
            "Assert" => Assert,
            "AssertError" => AssertError,
            "RandomElement" => RandomElement,
            "RandomSubset" => RandomSubset,
            "RandomSetOfSubsets" => RandomSetOfSubsets,
            "TLCEval" => Eval,
            "TLCNoOp" => NoOp,
            "SelectSeq" => SelectSeq,
            "SortSeq" => SortSeq,
            "Any" | "ANY" => Any,
            "Nat" => Naturals,
            "Int" => Integers,
            "STRING" => Strings,
            "Seq" => Sequences,
            "$Except" => Except,
            "$Pair" | "$Seq" => Tuple,
            "$RcdConstructor" => Record,
            "$SetOfRcds" => RecordSet,
            "$RcdSelect" => Apply,
            "$CartesianProd" => Cartesian,
            "$Case" => Case,
            ":>" => FunctionSingleton,
            "@@" => FunctionOverride,
            "IsFiniteSet" => IsFiniteSet,
            "Permutations" => Permutations,
            "IsABag" => IsABag,
            "BagToSet" => BagToSet,
            "SetToBag" => SetToBag,
            "BagIn" => BagIn,
            "CopiesIn" => CopiesIn,
            "BagCardinality" => BagCardinality,
            "~" | "\\lnot" => Not,
            "/\\" | "\\land" | "$ConjList" => And,
            "\\/" | "\\lor" | "$DisjList" => Or,
            "=>" => Implies,
            "<=>" | "\\equiv" => Equivalent,
            "=" => Eq,
            "#" | "/=" => Ne,
            "<" => Lt,
            "<=" | "=<" | "\\leq" => Le,
            ">" => Gt,
            ">=" | "\\geq" => Ge,
            "+" => Add,
            "-" => Sub,
            "*" => Mul,
            "\\div" => Div,
            "%" => Mod,
            "^" => Pow,
            "-." => Neg,
            "\\in" => In,
            "\\notin" => NotIn,
            "\\subseteq" => SubsetEq,
            "\\cup" | "\\union" => Union,
            "\\cap" | "\\intersect" => Intersection,
            "\\" => Difference,
            ".." => Range,
            "$SetEnumerate" => Set,
            "$Tuple" => Tuple,
            "$FcnApply" => Apply,
            "DOMAIN" => Domain,
            "Cardinality" => Cardinality,
            "Len" => Len,
            "Head" => Head,
            "Tail" => Tail,
            "Append" => Append,
            "\\o" => Concat,
            "SubSeq" => Subsequence,
            "UNION" => UnionAll,
            "SUBSET" => PowerSet,
            "$SetOfFcns" => FunctionSet,
            "UNCHANGED" => Unchanged,
            _ => return None,
        })
    }
}
